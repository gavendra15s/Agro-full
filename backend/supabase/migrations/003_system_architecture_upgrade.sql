-- 1. Farm Static Profile (permanent risk indicators)
CREATE TABLE IF NOT EXISTS farm_static_profile (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id BIGINT UNIQUE NOT NULL REFERENCES farms(id) ON DELETE CASCADE,
  elevation_meters DECIMAL(8,2) NOT NULL DEFAULT 1500.0,
  slope_degrees DECIMAL(5,2) NOT NULL DEFAULT 15.0,
  distance_to_river_km DECIMAL(6,2) NOT NULL DEFAULT 2.5,
  distance_to_coast_km DECIMAL(6,2) NOT NULL DEFAULT 250.0,
  landslide_susceptibility_class VARCHAR(20) NOT NULL CHECK (landslide_susceptibility_class IN ('low', 'medium', 'high')) DEFAULT 'medium',
  source VARCHAR(100) DEFAULT 'SRTM / Copernicus DEM + GSI Susceptibility',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_static_farm ON farm_static_profile(farm_id);

-- 2. Farm Climatology (10-Year Historical Trend from NASA POWER)
CREATE TABLE IF NOT EXISTS farm_climatology (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id BIGINT NOT NULL REFERENCES farms(id) ON DELETE CASCADE,
  month INT NOT NULL CHECK (month BETWEEN 1 AND 12),
  avg_heavy_rain_days DECIMAL(5,2) DEFAULT 0.0,
  temp_p10 DECIMAL(5,2) DEFAULT 10.0,
  temp_p50 DECIMAL(5,2) DEFAULT 20.0,
  temp_p90 DECIMAL(5,2) DEFAULT 30.0,
  source_years VARCHAR(50) DEFAULT '2014-2024 (NASA POWER)',
  summary_text TEXT,
  CONSTRAINT unique_farm_month UNIQUE (farm_id, month)
);
CREATE INDEX IF NOT EXISTS idx_climatology_lookup ON farm_climatology(farm_id, month);

-- 3. Availability Calendar with 15-Minute Hold Concurrency
CREATE TABLE IF NOT EXISTS availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id BIGINT NOT NULL REFERENCES farms(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('available', 'held', 'booked')) DEFAULT 'available',
  price DECIMAL(10,2) NOT NULL,
  held_until TIMESTAMPTZ,
  held_by_booking_id BIGINT REFERENCES bookings(id) ON DELETE SET NULL,
  CONSTRAINT unique_farm_date UNIQUE (farm_id, date)
);
CREATE INDEX IF NOT EXISTS idx_avail_date ON availability(farm_id, date, status);

-- 4. Forecast Snapshots (Normalized External Forecast Cache)
CREATE TABLE IF NOT EXISTS forecast_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grid_cell VARCHAR(50) NOT NULL,
  source VARCHAR(50) NOT NULL, -- 'Open-Meteo' | 'ECMWF' | 'GloFAS'
  issued_at TIMESTAMPTZ NOT NULL,
  valid_time TIMESTAMPTZ NOT NULL,
  rain_mm_24h DECIMAL(8,2) DEFAULT 0.0,
  temp_max_c DECIMAL(5,2),
  humidity_percent DECIMAL(5,2),
  wind_gust_kmh DECIMAL(6,2),
  river_discharge_percentile DECIMAL(5,2),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_grid_time_source UNIQUE (grid_cell, source, valid_time)
);
CREATE INDEX IF NOT EXISTS idx_forecast_lookup ON forecast_snapshots(grid_cell, valid_time);

-- 5. Recent Conditions (IMERG past 3/7 days rainfall + LHASA)
CREATE TABLE IF NOT EXISTS recent_conditions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id BIGINT NOT NULL REFERENCES farms(id) ON DELETE CASCADE,
  rainfall_past_3d_mm DECIMAL(8,2) DEFAULT 0.0,
  rainfall_past_7d_mm DECIMAL(8,2) DEFAULT 0.0,
  soil_moisture_proxy VARCHAR(20) DEFAULT 'normal', -- 'dry' | 'normal' | 'wet' | 'saturated'
  lhasa_class VARCHAR(20) DEFAULT 'low', -- 'low' | 'moderate' | 'high'
  recorded_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_recent_farm ON recent_conditions(farm_id, recorded_at);

-- 6. Official Alerts (SACHET CAP 1.2 XML & IMD Warnings)
CREATE TABLE IF NOT EXISTS official_alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cap_id VARCHAR(100) UNIQUE NOT NULL,
  source VARCHAR(50) NOT NULL, -- 'SACHET' | 'IMD' | 'CWC' | 'GSI' | 'INCOIS'
  event VARCHAR(100) NOT NULL,
  level VARCHAR(20) NOT NULL CHECK (level IN ('Yellow', 'Orange', 'Red')),
  level_code INT NOT NULL CHECK (level_code BETWEEN 1 AND 3),
  polygon_coordinates JSONB, -- Array of [lng, lat]
  district_code VARCHAR(50),
  district_name VARCHAR(100),
  state VARCHAR(100),
  headline VARCHAR(255) NOT NULL,
  description TEXT,
  effective TIMESTAMPTZ NOT NULL,
  expires TIMESTAMPTZ NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('Actual', 'Update', 'Cancel', 'Test')) DEFAULT 'Actual',
  raw_xml TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_alerts_active ON official_alerts(status, effective, expires);
CREATE INDEX IF NOT EXISTS idx_alerts_district ON official_alerts(district_name, state);

-- 7. Hazard Scores (The Precomputed Core Risk Engine Output)
CREATE TABLE IF NOT EXISTS hazard_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id BIGINT NOT NULL REFERENCES farms(id) ON DELETE CASCADE,
  hazard VARCHAR(30) NOT NULL CHECK (hazard IN ('landslide', 'flood', 'cyclone', 'heat', 'thunderstorm')),
  date DATE NOT NULL,
  level_code INT NOT NULL CHECK (level_code IN (-1, 0, 1, 2, 3)), -- -1 = Insufficient data, 0=Green, 1=Yellow, 2=Orange, 3=Red
  level_name VARCHAR(30) NOT NULL CHECK (level_name IN ('Green', 'Yellow', 'Orange', 'Red', 'Insufficient data')),
  confidence VARCHAR(20) NOT NULL CHECK (confidence IN ('high', 'medium', 'low', 'not_applicable')),
  horizon_label VARCHAR(30) NOT NULL CHECK (horizon_label IN ('Forecast', 'Early estimate', 'Historical trend', 'Insufficient data')),
  reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
  source_times JSONB NOT NULL DEFAULT '{}'::jsonb,
  disclaimer TEXT DEFAULT 'This is a rule-based risk estimate, not a guarantee of safety.',
  climatology_note TEXT,
  can_rebook_or_cancel BOOLEAN DEFAULT FALSE,
  computed_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_farm_hazard_date UNIQUE (farm_id, hazard, date)
);
CREATE INDEX IF NOT EXISTS idx_hazard_scores_lookup ON hazard_scores(farm_id, date);

-- 8. Incident Reports (Path B: Verified Photo Reports)
CREATE TABLE IF NOT EXISTS incident_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_code VARCHAR(50) UNIQUE NOT NULL,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  farm_id BIGINT REFERENCES farms(id) ON DELETE SET NULL,
  photo_url TEXT NOT NULL,
  device_lat DECIMAL(9,6) NOT NULL,
  device_lng DECIMAL(9,6) NOT NULL,
  photo_exif_lat DECIMAL(9,6),
  photo_exif_lng DECIMAL(9,6),
  photo_exif_time TIMESTAMPTZ,
  claimed_type VARCHAR(50) NOT NULL DEFAULT 'landslide',
  location_name VARCHAR(255),
  details TEXT,
  credibility_score DECIMAL(5,2) DEFAULT 0.0 CHECK (credibility_score BETWEEN 0.0 AND 100.0),
  score_band VARCHAR(20) NOT NULL CHECK (score_band IN ('low', 'medium', 'high')) DEFAULT 'low',
  status VARCHAR(30) NOT NULL CHECK (status IN ('pending_moderation', 'confirmed', 'rejected')) DEFAULT 'pending_moderation',
  moderator_note TEXT,
  reported_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_incidents_status ON incident_reports(status, score_band);

-- 9. Report Signals (Credibility Score Breakdown)
CREATE TABLE IF NOT EXISTS report_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES incident_reports(id) ON DELETE CASCADE,
  signal_name VARCHAR(100) NOT NULL,
  signal_value TEXT NOT NULL,
  weight DECIMAL(5,2) NOT NULL,
  score_points DECIMAL(5,2) NOT NULL,
  description TEXT
);
CREATE INDEX IF NOT EXISTS idx_signals_report ON report_signals(report_id);

-- 10. Moderation Actions (Human Moderator Audit Log)
CREATE TABLE IF NOT EXISTS moderation_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES incident_reports(id) ON DELETE CASCADE,
  moderator_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  decision VARCHAR(20) NOT NULL CHECK (decision IN ('confirm', 'reject', 'request_info')),
  reason TEXT NOT NULL,
  decided_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_moderation_report ON moderation_actions(report_id);

-- 11. Alert Deliveries (Dispatch log + "I'm safe" button tracking)
CREATE TABLE IF NOT EXISTS alert_deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id BIGINT REFERENCES official_alerts(id) ON DELETE CASCADE,
  recipient_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  recipient_name VARCHAR(100) NOT NULL,
  recipient_phone VARCHAR(30),
  recipient_email VARCHAR(255),
  channel VARCHAR(20) NOT NULL CHECK (channel IN ('Push', 'SMS', 'WhatsApp', 'Email')),
  status VARCHAR(20) NOT NULL CHECK (status IN ('sent', 'delivered', 'failed')) DEFAULT 'sent',
  is_safe_acked BOOLEAN DEFAULT FALSE,
  acked_at TIMESTAMPTZ,
  dispatched_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_deliveries_alert ON alert_deliveries(alert_id, is_safe_acked);

-- 12. Source Runs (Freshness Watcher for all External Data Adapters)
CREATE TABLE IF NOT EXISTS source_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name VARCHAR(50) NOT NULL,
  job_name VARCHAR(100) NOT NULL,
  last_attempt_at TIMESTAMPTZ DEFAULT NOW(),
  last_success_at TIMESTAMPTZ DEFAULT NOW(),
  is_healthy BOOLEAN DEFAULT TRUE,
  consecutive_failures INT DEFAULT 0,
  last_error TEXT,
  records_processed INT DEFAULT 0,
  freshness_limit_minutes INT DEFAULT 360,
  CONSTRAINT unique_source_job UNIQUE (source_name, job_name)
);

-- Extend bookings table to support holds and weather rebooking if columns missing
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'bookings' AND column_name = 'hold_expires_at') THEN
    ALTER TABLE bookings ADD COLUMN hold_expires_at TIMESTAMPTZ;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'bookings' AND column_name = 'rebook_offered_at') THEN
    ALTER TABLE bookings ADD COLUMN rebook_offered_at TIMESTAMPTZ;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'bookings' AND column_name = 'weather_risk_level') THEN
    ALTER TABLE bookings ADD COLUMN weather_risk_level VARCHAR(30);
  END IF;
END $$;
