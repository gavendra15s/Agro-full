-- -------------------------------------------------------------------------
-- 7. WARNINGS TABLE (ERD: WARNING / DFD D5 / CFD Warnings)
-- Automated CNN or Host Manual alerts triggering spatial radius overrides
-- -------------------------------------------------------------------------
